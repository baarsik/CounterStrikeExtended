"""Produce controlled UTF8/UTF16 cells; no locale or OS preference operations."""
from pathlib import Path

utf8 = [b'', b'A', b'ABC', b'A\0B', 'Жé漢'.encode(), '🙂'.encode(), 'A🙂Z'.encode(), b'\xef\xbb\xbfX',
        b'\xc0\x80', b'\xc0\xaf', b'\xc1\xbf', b'\xe0\x80\x80', b'\xed\xa0\x80', b'\xed\xbf\xbf',
        b'\xed\xa0\xbd\xed\xb9\x82', b'\xf0\x80\x80\x80', b'\xf4\x90\x80\x80', b'\xf5\x80\x80\x80',
        b'\xe2', b'\xe2\x82', b'\xe2A\x82', b'\xf0\x9f', b'\xf0\x9f\x99', b'\xf0A\x99\x82',
        b'\x80\xbf', b'\xfe\xff', b'\xc2\x80', b'\xe0\xa0\x80', b'\xf0\x90\x80\x80',
        b'\xf4\x8f\xbf\xbf', b'\xef\xbf\xbe\xef\xbf\xbf']
utf8 += [bytes([value]) for value in range(1, 256)]
wide = [[0], [0x41, 0], [0x41, 0, 0x42, 0], [0x416, 0xe9, 0x6f22, 0], [0xd83d, 0xde42, 0],
        [0x41, 0xd83d, 0xde42, 0x5a, 0], [0xd800, 0], [0xdc00, 0], [0xd800, 0xd800, 0],
        [0xdc00, 0xdc00, 0], [0xd800, 0x41, 0], [0xdc00, 0xd800, 0xdc00, 0],
        [0xd800, 0xd800, 0xdc00, 0], [0xdbff, 0xdfff, 0], [0xd800, 0xdc00, 0],
        [0xfeff, 0xfffe, 0xffff, 0], [0xd800, 0, 0xdc00, 0]]
output = ['// Controlled corpus; generated by make_corpus.py.', 'constexpr const char* Utf8Inputs[] = {']
output += ['    "' + ''.join('\\x%02x' % value for value in data) + '",' for data in utf8]
output += ['};', 'constexpr std::uint16_t WideInputs[][8] = {']
output += ['    {' + ', '.join('0x%04x' % value for value in data) + '},' for data in wide]
output += ['};']
Path(__file__).with_name('corpus.h').write_text('\n'.join(output) + '\n')
