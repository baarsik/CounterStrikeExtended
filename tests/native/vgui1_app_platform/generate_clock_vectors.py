"""Independent arbitrary-precision oracle; no clock/provider execution."""
from pathlib import Path
import hashlib,json,random
rng=random.Random(0x43534510)
values=[(0,1,1),(1,1,1),(1000000,1,1),(2**64-1,2**32-1,1),(2**64-1,1,2**32-1)]
for bit in (0,1,31,32,33,62,63):
 for offset in (-1,0,1):
  ticks=max(0,min(2**64-1,2**bit+offset))
  values.append((ticks,2**32-1,2**32-1))
for _ in range(512):
 values.append((rng.getrandbits(64),rng.randint(1,2**32-1),rng.randint(1,2**32-1)))
rows=[]
for ticks,numerator,denominator in values:
 expected=(ticks*numerator//(denominator*1000000))%(2**32)
 rows.append((ticks,numerator,denominator,expected))
text='// Generated by independent Python arbitrary-precision integer oracle.\n'
text+='struct ClockVector {\n    std::uint64_t ticks;\n    std::uint32_t numerator;\n    std::uint32_t denominator;\n    std::uint32_t expected;\n};\n'
text+='constexpr ClockVector ClockVectors[] = {\n'
for row in rows:
 text+='    {'+str(row[0])+'ull, '+', '.join(str(value)+'u' for value in row[1:])+'},\n'
text+='};\n'
Path(__file__).with_name('clock_vectors.h').write_text(text)
print(json.dumps({'vectors':len(rows),'sha256':hashlib.sha256(text.encode()).hexdigest()}))
