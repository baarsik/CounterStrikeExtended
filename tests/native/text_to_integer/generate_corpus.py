"""Author encoded input cases independently of any proposed conversion implementation."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
cases = []

def add(kind, name, units):
    cases.append({'kind': kind, 'name': name, 'units': list(units)})

texts = ['', '0', '-0', '+0', '1', '-1', '+1', '42', '00042', ' 42', '\t\n\v\f\r 42',
         ' +42tail', ' -42tail', '+', '-', '++1', '--1', '+-1', '-+1', '+ 1', '-\t1',
         '1 2', '42.75', '1e9', '0x10', '-0x10', '0b11', '077', '12abc', 'abc12',
         '76561198000000000', 'STEAM_0:1:12345', '[U:1:12345]']
for bits in (31, 32, 63, 64):
    for delta in (-2, -1, 0, 1, 2):
        value = 2**bits + delta
        texts.extend([str(value), '-' + str(value), '+' + str(value)])
texts += ['9' * 4096, '-' + '9' * 4096, '+' + '0' * 4096 + '42', '0' * 4096 + '2147483648',
          '-' + '0' * 4096 + '9223372036854775809', '9' * 4096 + 'tail']
for index, text in enumerate(dict.fromkeys(texts)):
    add('narrow', 'decimal-' + str(index), text.encode('ascii'))
    add('wide', 'decimal-' + str(index), map(ord, text))
for unit in [0, 8, 9, 10, 11, 12, 13, 28, 31, 32, 33, 127, 128, 133, 160, 255]:
    add('narrow', 'byte-prefix-' + str(unit), [unit, ord('4'), ord('2')])
for text in ['\u00a042', '\u168042', '\u200042', '\u202f42', '\u300042', '\uff0b42', '\uff0d42',
             '\u221242', '\uff1142', '\u066142', '\u06f142', '\u096742', '1\uff12', '\uff11\uff12',
             '\u0661\u0662', '\ud80042', '\udc0042', '\ud83d\ude0042', '42\ud8009', '\uffff42']:
    add('wide', 'unicode-' + str(len(cases)), map(ord, text))
    if not any(0xd800 <= ord(unit) <= 0xdfff for unit in text):
        add('narrow', 'utf8-' + str(len(cases)), text.encode('utf-8'))
# Boundaries observed in the first exhaustive real-CRT probe; measure every position, not assumed outputs.
digit_starts = [0x30, 0x660, 0x6f0, 0x966, 0x9e6, 0xa66, 0xae6, 0xb66, 0xc66, 0xce6,
                0xd66, 0xe50, 0xed0, 0xf20, 0x1040, 0x17e0, 0x1810, 0xff10]
space_ranges = [(9, 13), (0x20, 0x20), (0x85, 0x85), (0xa0, 0xa0), (0x1680, 0x1680),
                (0x180e, 0x180e), (0x2000, 0x200a), (0x2028, 0x2029), (0x202f, 0x202f),
                (0x205f, 0x205f), (0x3000, 0x3000)]
boundaries = set()
for zero in digit_starts:
    boundaries.update([zero - 1, zero, zero + 1, zero + 9, zero + 10])
for first, last in space_ranges:
    boundaries.update([first - 1, first, last, last + 1])
for unit in sorted(boundaries):
    for prefix, suffix in [([ord('-')], [ord('7')]), ([ord('1')], [ord('3')]),
                           ([ord(' '), ord('+')], [ord('7')])]:
        add('wide', 'range-boundary-' + str(len(cases)), prefix + [unit] + suffix)
for kind in ('narrow', 'wide'):
    add(kind, 'embedded-nul-' + kind, [ord('1'), ord('2'), 0, ord('9'), ord('9')])
args.output.mkdir(parents=True, exist_ok=True)
(args.output / 'corpus.json').write_text(json.dumps(cases, indent=2) + '\n')
lines = ['// Generated by generate_corpus.py; raw byte/code-unit input, no locale or encoding conversion.',
         '#pragma once', '#include <cstdint>', '#include <vector>',
         'struct InputCase { const char* name; bool wide; std::vector<std::uint32_t> units; };',
         'inline std::vector<InputCase> InputCases() {', '    return {']
for row in cases:
    lines.append('        {"%s", %s, {%s}},' % (row['name'], 'true' if row['kind'] == 'wide' else 'false',
                 ','.join(hex(unit) for unit in row['units'])))
lines += ['    };', '}', '']
(args.output / 'input_cases.h').write_text('\n'.join(lines))
print('Encoded input cases:', len(cases))
