"""Generate engine/game ABI layout facts from the actual shared C declarations."""
from pathlib import Path
import re
from saved_callback_catalog import clean, write_generated

# Contract identities are stable; membership comes from these owning headers.
TABLES = [
    ('EngineFunctions', 'enginefuncs_t', 'src/common/game_engine_functions.h'),
    ('GameFunctions', 'DLL_FUNCTIONS', 'src/engine/eiface.h'),
    ('NewGameFunctions', 'NEW_DLL_FUNCTIONS', 'src/engine/eiface.h'),
    ('SaveField', 'TYPEDESCRIPTION', 'src/common/game_save_descriptions.h'),
    ('SaveBuffer', 'SAVERESTOREDATA', 'src/engine/eiface.h'),
    ('EntitySaveEntry', 'ENTITYTABLE', 'src/engine/eiface.h'),
    ('LevelConnection', 'LEVELLIST', 'src/engine/eiface.h'),
    ('Globals', 'globalvars_t', 'src/engine/progdefs.h'),
    ('EntityVariables', 'entvars_t', 'src/engine/progdefs.h'),
    ('EntityRecord', 'edict_t', 'src/engine/edict.h'),
    ('Trace', 'TraceResult', 'src/engine/eiface.h'),
]


def struct_fields(source, name):
    text = re.sub(r'^\s*#[^\n]*', '', clean(source), flags=re.M)
    for match in re.finditer(r'\bstruct\s*(\w+)?\s*\{', text):
        start = match.end()
        end = start
        depth = 1
        while end < len(text) and depth:
            depth += (text[end] == '{') - (text[end] == '}')
            end += 1
        tail = text[end:text.index(';', end)].strip()
        if tail != name and not (name == 'edict_t' and match[1] == 'edict_s'):
            continue
        body = text[start:end - 1]
        if '{' in body or '}' in body:
            raise ValueError('Unsupported nested ABI member in ' + name)
        fields = []
        for statement in body.split(';'):
            statement = statement.strip()
            if not statement:
                continue
            function = re.search(r'\(\s*\*\s*(\w+)\s*\)', statement)
            if function:
                fields.append(function[1])
                continue
            for member in statement.split(','):
                found = re.search(r'\b(\w+)\s*(?:\[[^\]]+\]\s*)*$', member)
                if not found or '(' in member or ')' in member or ':' in member:
                    raise ValueError('Unsupported ABI member in ' + name + ': ' + statement)
                fields.append(found[1])
        if not fields or len(fields) != len(set(fields)):
            raise ValueError('Empty or duplicate ABI fields in ' + name)
        return fields
    raise ValueError('Missing shared ABI declaration: ' + name)


def generate(root):
    lines = ['// Generated by tools/generate_runtime_sources.py from shared declarations; do not edit.',
             '#pragma once', '#include "cse_module_abi.h"', '', 'namespace cse::abi {', '',
             '// Stable table identifiers for the engine/game boundary.', 'enum class GameTable : std::uint32_t {']
    for index, (identity, name, header) in enumerate(TABLES, 1):
        lines.append(f'    {identity} = {index},')
    lines += ['};', '', 'constexpr Descriptor GameModuleDescriptor = Describe({']
    counts = {}
    for identity, name, header in TABLES:
        fields = struct_fields((root / header).read_text(errors='replace'), name)
        counts[name] = len(fields)
        lines += [f'    {{static_cast<std::uint32_t>(GameTable::{identity}), 0, LayoutHash({{',
                  f'        sizeof({name}), alignof({name}),']
        for field in fields:
            lines += [f'        offsetof({name}, {field}), sizeof((({name} *)nullptr)->{field}),',
                      f'        alignof(decltype((({name} *)nullptr)->{field})),']
        lines.append('    })},')
    lines += ['});', '', '} // namespace cse::abi', '']
    write_generated(root / 'src/common/generated_game_module_layouts.h', '\n'.join(lines))
    return counts
