"""Generate ReGameDLL's build sources and typed callbacks from the pinned source."""

import argparse
from collections import defaultdict
from pathlib import Path
import re

from saved_callback_catalog import KINDS, TYPES, inventory, write_generated


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / 'src/external/regamedll/regamedll'
GENERATED = ROOT / 'src/cstrike/regamedll/generated_saved_callbacks.inc'
GENERATED_SOURCES = ROOT / 'cmake/targets/cs_server/ReGameDLLSources.cmake'


def build_sources(source):
    cmake = (source / 'CMakeLists.txt').read_text()
    sources = {}
    for name in ('GAMEDLL_SRCS', 'ENGINE_SRCS', 'SHARED_SRCS'):
        source_list = re.search(rf'^set\({name}\n(.*?)^\)', cmake, re.M | re.S)
        if not source_list:
            raise ValueError(f'Missing ReGameDLL source list {name}')
        paths = []
        for line in source_list[1].splitlines():
            entry = line.strip()
            if not entry or entry.startswith('#'):
                continue
            match = re.fullmatch(r'"([^"\n]+\.cpp)"\s*(?:#.*)?', entry)
            if not match:
                raise ValueError(f'Unexpected {name} source entry: {entry}')
            paths.append(Path(match[1]))
        if not paths:
            raise ValueError(f'Empty ReGameDLL source list {name}')
        sources[name] = paths

    # CSE supplies filesystem queries through engine callbacks and selects
    # the platform implementation in ReGameDLLTarget.cmake.
    excluded = {Path('public/FileSystem.cpp'), Path('public/tier0/platform_posix.cpp')}
    support = dict.fromkeys(sources['ENGINE_SRCS'] + sources['SHARED_SRCS'])
    return sources['GAMEDLL_SRCS'], [path for path in support if path not in excluded]


def registrations(source, paths):
    report = inventory(source, 'cs', 'regamedll', [source / path for path in paths],
                       headers_root=source / 'dlls')
    expected_fields = {(kind['owner'], kind['field']) for kind in KINDS.values()}
    actual_fields = {(field['cpp_class'], field['field']) for field in report['function_fields']}
    if actual_fields != expected_fields:
        raise ValueError(f'Unexpected ReGameDLL callback fields: {actual_fields ^ expected_fields}')

    # Unsupported callback expressions must fail generation unless hard-disabled.
    unknown = [site for item in report['unresolved'] for site in item['sites'] if site['guard'] != '0']
    unknown += [site for site in report['unqualified_nonnull_sites'] if site['guard'] != '0']
    unknown += [site for site in report['direct_assignments'] if site['guard'] != '0']
    if unknown:
        raise ValueError(f'Uncatalogued ReGameDLL callback assignments: {unknown}')

    hosts = defaultdict(list)
    for callback in report['canonical_callbacks']:
        declaration = callback['declaration']
        name = callback['canonical_name']
        if callback['virtual_in_hierarchy'] or declaration['guard']:
            raise ValueError(f'Unsupported ReGameDLL callback: {name}')
        host = Path(declaration['path'])
        if host.suffix == '.h':
            sites = [Path(site['path']) for site in callback['sites'] if site['path'] and site['guard'] != '0'
                     and site['source_category'] == 'compiled_source']
            host = min(sites, default=host.with_suffix('.cpp'))
        if host not in paths:
            raise ValueError(f'ReGameDLL callback host for {name} is absent: {host}')
        hosts[host].append(callback)
    return hosts


def source_name(path):
    return '_'.join(path.with_suffix('').parts)


def render(hosts):
    lines = ['// Generated by tools/generate_regamedll_saved_callbacks.py; do not edit.', '']
    for path, callbacks in sorted(hosts.items()):
        lines.append(f'#define CSE_REGAMEDLL_CALLBACKS_{source_name(path)} \\')
        for index, callback in enumerate(callbacks):
            kind = callback['kind']
            name = callback['canonical_name']
            declaration = callback['declaration']
            method = f"&{declaration['declaring_class']}::{declaration['method']}"
            continuation = ' \\' if index < len(callbacks) - 1 else ''
            lines.append(f'    CSE_REGAMEDLL_CALLBACK({kind}, "{name}", {TYPES[kind]}, \\')
            lines.append(f'        {method}){continuation}')
        lines.append('')

    lines.append('#define CSE_FOR_EACH_REGAMEDLL_CALLBACK_SOURCE(apply) \\')
    for index, path in enumerate(sorted(hosts)):
        continuation = ' \\' if index < len(hosts) - 1 else ''
        lines.append(f'    apply({source_name(path)}){continuation}')
    return '\n'.join(lines) + '\n'


def render_sources(game, support, hosts):
    lines = ['# Generated by tools/generate_regamedll_saved_callbacks.py; do not edit.', '']
    for name, paths in (('GAME', game), ('SUPPORT', support), ('CALLBACK', sorted(hosts))):
        lines.append(f'set(CSE_REGAMEDLL_{name}_SOURCES')
        lines.extend(f'  "{path.as_posix()}"' for path in paths)
        lines.extend((')', ''))
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=DEFAULT_SOURCE,
                        help='ReGameDLL CMake source directory, inside the checkout or staged tree')
    parser.add_argument('--check', action='store_true', help='Verify the generated files without writing them')
    args = parser.parse_args()
    source = args.source.resolve()
    game, support = build_sources(source)
    hosts = registrations(source, game + support)
    outputs = ((GENERATED, render(hosts)), (GENERATED_SOURCES, render_sources(game, support, hosts)))
    for path, generated in outputs:
        if args.check:
            if not path.is_file() or path.read_text() != generated:
                parser.exit(1, f'{path.relative_to(ROOT)} is stale\n')
        else:
            write_generated(path, generated)
    print(f'{sum(map(len, hosts.values()))} ReGameDLL callbacks in {len(hosts)} translation units')


if __name__ == '__main__':
    main()
